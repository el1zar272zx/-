def items(service: Service) -> list[str]:
    return [x.strip() for x in (service.contra or "").splitlines() if x.strip()]


def needs_check(service: Service) -> bool:
    return bool(items(service)) or bool(getattr(service, "consent", False))


async def seed() -> None:
    """Одноразово додає типові протипоказання до послуг, у яких їх ще немає."""
    async with session_scope() as session:
        if await session.get(SalonInfo, "contra_seeded") is not None:
            return
        services = (await session.execute(select(Service))).scalars().all()
        for svc in services:
            if svc.contra:
                continue
            name = svc.name.casefold()
            for keys, lines, consent in DEFAULTS:
                if any(k in name for k in keys):
                    svc.contra = "\n".join(lines)
                    svc.consent = consent
                    break
        session.add(SalonInfo(key="contra_seeded", value="1"))
