EXACT: dict[str, str] = dict(EXACT2)

_ORDERED = sorted(RU.items(), key=lambda kv: len(kv[0]), reverse=True)
_BOLD = [(f"<b>{k}</b>", f"<b>{v}</b>") for k, v in EXACT.items()]


def to_ru(text: str) -> str:
    ex = EXACT.get(text)
    if ex is not None:
        return ex
    for ua, ru in _BOLD:
        if ua in text:
            text = text.replace(ua, ru)
    for ua, ru in _ORDERED:
        if ua in text:
            text = text.replace(ua, ru)
    return text


# ---------- Автоматичний переклад вихідних повідомлень ----------

# (мова, простий_режим, дійсно_до)
_CACHE: dict[int, tuple[str, bool, float]] = {}
_TTL = 300.0
PENDING: dict[int, str] = {}  # мова, обрана до реєстрації (клієнта ще немає в базі)


def set_cached_lang(telegram_id: int, lang: str, simple: bool | None = None) -> None:
    old = _CACHE.get(telegram_id)
    keep = old[1] if (simple is None and old) else bool(simple)
    _CACHE[telegram_id] = (lang, keep, time.monotonic() + _TTL)


def set_cached_simple(telegram_id: int, simple: bool) -> None:
    old = _CACHE.get(telegram_id)
    _CACHE[telegram_id] = ((old[0] if old else "uk"), simple, time.monotonic() + _TTL)


async def _prefs_of(chat_id: int) -> tuple[str, bool]:
    hit = _CACHE.get(chat_id)
    if hit and hit[2] > time.monotonic():
        return hit[0], hit[1]
    from sqlalchemy import select

    from .database import session_scope
    from .models import Client

    async with session_scope() as session:
        row = (await session.execute(select(Client.lang, Client.simple).where(Client.telegram_id == chat_id))).first()
    if row is None:
        lang, simple = PENDING.get(chat_id, "uk"), False
    else:
        lang, simple = row[0] or "uk", bool(row[1])
    _CACHE[chat_id] = (lang, simple, time.monotonic() + _TTL)
    return lang, simple


async def _lang_of(chat_id: int) -> str:
    return (await _prefs_of(chat_id))[0]


def install_translation(bot) -> None:
    """Переклад вихідних повідомлень для клієнтів з мовою ru й простий режим меню."""
    from aiogram.client.session.middlewares.base import BaseRequestMiddleware
    from aiogram.types import InlineKeyboardMarkup, ReplyKeyboardMarkup

    class LangRequestMiddleware(BaseRequestMiddleware):
        async def __call__(self, make_request, bot, method):  # type: ignore[override]
            try:
                chat_id = getattr(method, "chat_id", None)
                if isinstance(chat_id, int) and chat_id > 0:
                    lang, simple = await _prefs_of(chat_id)
                    markup = getattr(method, "reply_markup", None)
                    if simple and isinstance(markup, ReplyKeyboardMarkup):
                        from client_bot.keyboards import BTN_BOOK, BTN_QUIZ, simple_reply_kb

                        flat = [b.text for row in markup.keyboard for b in row]
                        if BTN_BOOK in flat and BTN_QUIZ in flat:  # це головне меню
                            method.reply_markup = markup = simple_reply_kb()
                    if lang == "ru":
                        for attr in ("text", "caption"):
                            val = getattr(method, attr, None)
                            if isinstance(val, str):
                                setattr(method, attr, to_ru(val))
                        if isinstance(markup, InlineKeyboardMarkup):
                            rows = [
                                [b.model_copy(update={"text": to_ru(b.text)}) for b in row]
                                for row in markup.inline_keyboard
                            ]
                            method.reply_markup = markup.model_copy(update={"inline_keyboard": rows})
                        elif isinstance(markup, ReplyKeyboardMarkup):
                            rows = [
                                [b.model_copy(update={"text": to_ru(b.text)}) for b in row]
                                for row in markup.keyboard
                            ]
                            method.reply_markup = markup.model_copy(update={"keyboard": rows})
            except Exception:
                logger.exception("Не вдалося перекласти повідомлення, надсилаю як є")
            return await make_request(bot, method)

    bot.session.middleware(LangRequestMiddleware())
