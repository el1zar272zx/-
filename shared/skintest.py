def result(answers: list[str]) -> str:
    """Тип шкіри за найчастішою відповіддю (при рівності перший за порядком)."""
    counts: dict[str, int] = {}
    for a in answers:
        counts[a] = counts.get(a, 0) + 1
    if not counts:
        return "n"
    best = max(counts.values())
    for a in answers:
        if counts[a] == best:
            return a
    return "n"
