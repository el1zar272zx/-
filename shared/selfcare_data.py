def compat(name_a: str, name_b: str) -> tuple[str, T2]:
    """Вердикт і текст для пари послуг за груповими правилами."""
    ta, tb = tags_of(name_a), tags_of(name_b)
    if "intim" in ta or "intim" in tb:
        return "ask", INTIM_TEXT
    if not ta or not tb:
        return "ask", ASK_TEXT
    if (name_a or "").strip() == (name_b or "").strip():
        return "ok", (
            "Це та сама процедура: її роблять курсом, інтервал між сеансами призначає майстер.",
            "Это та же процедура: её делают курсом, интервал между сеансами назначает мастер.",
        )
    for x in ta:
        for y in tb:
            rule = _RULES.get(frozenset((x, y)))
            if rule is not None:
                return rule
    return "ask", ASK_TEXT


