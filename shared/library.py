async def seed() -> None:
    """Одноразово заповнює довідник стартовими матеріалами. Майстер може все редагувати."""
    async with session_scope() as session:
        if await session.get(SalonInfo, "library_seeded") is not None:
            return
        for kind, items in (("tip", TIPS), ("ex", EXERCISES), ("term", TERMS)):
            for title, text in items:
                session.add(LibraryItem(kind=kind, title=title, text=text))
        session.add(SalonInfo(key="library_seeded", value="1"))


async def items(session: AsyncSession, kind: str, active_only: bool = True) -> list[LibraryItem]:
    q = select(LibraryItem).where(LibraryItem.kind == kind)
    if active_only:
        q = q.where(LibraryItem.active.is_(True))
    return list((await session.execute(q.order_by(LibraryItem.id))).scalars().all())


async def get(session: AsyncSession, item_id: int) -> LibraryItem | None:
    return await session.get(LibraryItem, item_id)


async def add(session: AsyncSession, kind: str, title: str, text: str) -> LibraryItem:
    it = LibraryItem(kind=kind, title=title[:150], text=text)
    session.add(it)
    await session.flush()
    return it


async def remove(session: AsyncSession, item_id: int) -> None:
    await session.execute(delete(LibraryItem).where(LibraryItem.id == item_id))


async def toggle(session: AsyncSession, item_id: int) -> None:
    it = await session.get(LibraryItem, item_id)
    if it is not None:
        it.active = not it.active


async def next_tip() -> LibraryItem | None:
    """Наступна порада тижня по колу (лічильник у налаштуваннях)."""
    async with session_scope() as session:
        tips = await items(session, "tip")
        if not tips:
            return None
        row = await session.get(SalonInfo, "tip_idx")
        idx = int(row.value) if row and row.value.isdigit() else 0
        tip = tips[idx % len(tips)]
        if row is None:
            session.add(SalonInfo(key="tip_idx", value=str(idx + 1)))
        else:
            row.value = str(idx + 1)
        return tip
